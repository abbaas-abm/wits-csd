// Minimal service worker. Required for PWA installability and Web Push.
// It performs no caching, so it never serves stale content.

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("fetch", () => {
  // Network pass-through.
});

self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { body: event.data ? event.data.text() : "" };
  }

  const title = data.title || "Centre for Student Development";
  const options = {
    body: data.body || "",
    icon: "/icons/notification.png",
    badge: "/icons/badge.png",
    data: { url: data.url || "/" },
  };

  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || "/";

  // Announcement links can point to other sites; open those in a new window
  // rather than navigating an existing tab of the platform away.
  const target = new URL(url, self.location.origin);
  if (target.origin !== self.location.origin) {
    event.waitUntil(self.clients.openWindow(target.href));
    return;
  }

  event.waitUntil(
    self.clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((clients) => {
        for (const client of clients) {
          if (client.url.includes(self.location.origin) && "focus" in client) {
            client.navigate(url);
            return client.focus();
          }
        }
        return self.clients.openWindow(url);
      }),
  );
});
